#!/usr/bin/env python3
"""Summarize every trial and verify deterministic paired observations."""
import argparse
import csv
import pathlib
import statistics

parser = argparse.ArgumentParser()
parser.add_argument("capture", type=pathlib.Path)
args = parser.parse_args()
root = args.capture


def rows(name):
    with (root / f"{name}.csv").open() as stream:
        return list(csv.DictReader(line for line in stream if not line.startswith("#")))


def spread(values, digits=2):
    return f"{statistics.mean(values):.{digits}f} [{min(values):.{digits}f}–{max(values):.{digits}f}]"


def paired(data, keys, observed):
    baseline = {tuple(r[k] for k in keys) + (r["cache"].removeprefix("baseline-"),): r
                for r in data if r["cache"].startswith("baseline-")}
    checked = 0
    for r in data:
        if not r["cache"].startswith("candidate-"):
            continue
        key = tuple(r[k] for k in keys) + (r["cache"].removeprefix("candidate-"),)
        old = baseline[key]
        for field in observed:
            assert old[field] == r[field], (key, field, old[field], r[field])
        checked += 1
    return checked


hits = rows("hitrate")
adapt = rows("adapt")
embedded = rows("embedded")
count = paired(hits, ["trace", "seed", "type", "capacity"], ["ops", "hits", "resident"])
adapt_count = paired(adapt, ["capacity", "phase"], ["ops", "hits", "resident"])
embedded_count = paired(embedded, ["trace", "seed", "capacity"], ["ops", "hits", "resident"])
lines = [
    f"# Paired results: {root.name}", "",
    "Generated by `evaluation/report.py`; all trials included. Values are mean [min–max].",
    "See metadata.json for compiler/CPU/source provenance and CSV files for raw observations.", "",
    f"Deterministic parity: **{count} hit-rate, {adapt_count} adaptation and {embedded_count} host-routing/sensor rows** match their published baseline in hits and residency.",
    "This parity is specific to these single-thread traces/capacities, not a concurrency proof.", "",
    "## Hit rate (%) — u64/u64, 65,536 nominal slots, 2M cache-aside ops", "",
    "| Trace | Candidate typed/concurrent | Candidate sharded | LRU | QuickCache | Moka |",
    "|---|---:|---:|---:|---:|---:|",
]
for trace in dict.fromkeys(r["trace"] for r in hits):
    values = []
    for name in ["candidate-typed", "candidate-sharded", "lru", "quick", "moka"]:
        values.append(spread([100 * int(r["hits"]) / int(r["ops"]) for r in hits if r["trace"] == trace and r["cache"] == name]))
    lines.append(f"| {trace} | " + " | ".join(values) + " |")
lines += ["", "## Throughput — Mops/s, nominal 5% writes (actual counts in CSV)", "",
          "All maps use synchronous adapters; LRU is mutex-wrapped. No miss filling. Scheduling",
          "can change concurrent hit counts and event loss. Spread is descriptive, not a significance test.", "",
          "| Type/threads | Baseline concurrent | Candidate concurrent | Baseline sharded | Candidate sharded | LRU | QuickCache | Moka |",
          "|---|---:|---:|---:|---:|---:|---:|---:|"]
throughput = rows("throughput")
for shape in ["u32", "u64"]:
    for threads in ["1", "4", "8"]:
        values = []
        for name in ["baseline-concurrent", "candidate-concurrent", "baseline-sharded", "candidate-sharded", "lru", "quick", "moka"]:
            values.append(spread([float(r["mops"]) for r in throughput if r["type"] == shape and r["threads"] == threads and r["cache"] == name]))
        lines.append(f"| {shape}/{threads}T | " + " | ".join(values) + " |")
lines += ["", "## Fresh-process Linux RSS", "", "One process per cache/type; allocator/page dependent, not exact allocated bytes.", "",
          "| Type/cache | Residents | Bytes/nominal slot | Bytes/resident |", "|---|---:|---:|---:|"]
for r in rows("memory"):
    lines.append(f"| {r['type']}/{r['cache']} | {r['resident']} | {r['bytes_per_slot']} | {r['bytes_per_resident']} |")
lines += ["", "## Growth boundary — one million u32 keys", "",
          "| Buckets/shard | Baseline residents | Candidate residents |", "|---:|---:|---:|"]
boundary = rows("boundary")
for buckets in dict.fromkeys(r["buckets_per_shard"] for r in boundary):
    pair = {r["cache"]: r["resident"] for r in boundary if r["buckets_per_shard"] == buckets}
    lines.append(f"| {buckets} | {pair['baseline-sharded']} | {pair['candidate-sharded']} |")
lines += ["", "## Policy adaptation", "", "| Capacity/cache | Shift hit rate (%) | Post-scan hit rate (%) |", "|---|---:|---:|"]
for cap in dict.fromkeys(r["capacity"] for r in adapt):
    for name in ["candidate-typed", "candidate-concurrent", "candidate-sharded", "lru", "quick", "moka"]:
        selected = {r["phase"]: r for r in adapt if r["capacity"] == cap and r["cache"] == name}
        if not selected:
            continue
        values = [f"{100 * int(selected[p]['hits']) / int(selected[p]['ops']):.2f}" for p in ["shift", "post_scan"]]
        lines.append(f"| {cap}/{name} | " + " | ".join(values) + " |")
lines += ["", "The four-slot probe reproduces the no-aging trade-off, not a resize/buffer defect.",
          "Post-scan measures ten hot-set passes after a 3×capacity cold scan; see adapt.csv for counts.", "",
          "## Host writer/reader contention", "",
          "One always-resident key gives identical hit work; all samples must be hits. Sample",
          "recording is outside map/LRU guards. See active-writer sample counts in CSV: a ready",
          "barrier does not guarantee simultaneous CPU execution. These are **not ISR bounds**.", "",
          "| Cache | Read p99 ns, mean [min–max] |", "|---|---:|"]
contention = rows("contention")
for name in dict.fromkeys(r["cache"] for r in contention):
    lines.append(f"| {name} | {spread([int(r['p99_ns']) for r in contention if r['cache'] == name], 0)} |")
(root / "report.md").write_text("\n".join(lines) + "\n")
print(f"Verified paired rows; wrote {root / 'report.md'}")
